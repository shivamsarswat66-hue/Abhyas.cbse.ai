export function buildPaper({ subject, mode, chapter, count = 20 }) {
  let pool = QUESTIONS.filter(q => q.subject === subject)
  if (mode === 'chapter' && chapter) pool = pool.filter(q => q.chapter === chapter)
  if (mode === 'expected') pool = pool.filter(q => q.expected)
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  const n = mode === 'full' ? Math.min(25, Math.max(shuffled.length, 8)) : Math.min(count, shuffled.length)
  const picked = shuffled.slice(0, Math.max(n, Math.min(8, shuffled.length)))
  if (picked.length < 8) {
    const extra = QUESTIONS.filter(q => q.subject === subject && !picked.includes(q))
    picked.push(...extra.slice(0, 8 - picked.length))
  }
  return picked
}
